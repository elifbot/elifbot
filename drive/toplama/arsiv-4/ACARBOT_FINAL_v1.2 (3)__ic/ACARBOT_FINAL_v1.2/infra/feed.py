import asyncio
import aiohttp

class MarketDataFeed:
    def __init__(self, ws_url, rest_fallback_url):
        self.ws_url = ws_url
        self.rest_fallback_url = rest_fallback_url
        self.is_connected = False
        self.last_price_cache = {}

    async def connect_ws(self):
        self.is_connected = True
        # WebSocket initialization logic here
        pass

    async def fetch_fallback_price(self, symbol):
        """REST Backup price source when WebSocket experiences disconnection or lag"""
        async with aiohttp.ClientSession() as session:
            try:
                async with session.get(f"{self.rest_fallback_url}/ticker?symbol={symbol}") as resp:
                    if resp.status == 200:
                        data = await resp.json()
                        price = float(data.get('price', 0))
                        self.last_price_cache[symbol] = price
                        return price
            except Exception:
                return self.last_price_cache.get(symbol, None)

