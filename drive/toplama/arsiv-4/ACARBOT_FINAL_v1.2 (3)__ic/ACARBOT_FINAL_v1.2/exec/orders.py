import uuid

class OrderExecutor:
    def __init__(self, exchange_client):
        self.exchange = exchange_client
        self.active_orders = {}

    def generate_client_order_id(self, strategy_name):
        return f"ACAR_{strategy_name}_{uuid.uuid4().hex[:8]}"

    def place_reduce_only_stop(self, symbol, side, amount, stop_price):
        """Places an exchange-side reduce-only stop loss order to protect equity if bot crashes"""
        order_params = {
            'symbol': symbol,
            'side': 'SELL' if side == 'LONG' else 'BUY',
            'type': 'STOP_MARKET',
            'amount': amount,
            'stopPrice': stop_price,
            'params': {'reduceOnly': True}
        }
        return order_params

    def reconcile_state_on_startup(self, local_positions):
        """Reconciles active positions on the exchange with local internal memory ledger"""
        exchange_positions = self.exchange.fetch_positions()
        synchronized_ledger = {}
        for pos in exchange_positions:
            symbol = pos['symbol']
            if symbol in local_positions:
                synchronized_ledger[symbol] = pos
        return synchronized_ledger

